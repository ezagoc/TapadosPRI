"""Estimates by succession on the headline estimand: tables/md_by_succession.tex.

For each succession, the average of the event-study contrasts over the four years after the election
(event_study_by_succession.csv, outcome rank), the numbers of followers (sample_by_succession.csv), and the
pooled estimate without that succession. Successions are weighted by the designee's followers' shares, the main
estimand since 3 November 2026 (TAPADOS_SUCCESSION_WEIGHTS=person); --equal-weights reproduces the earlier equal mean. Run from the repo root:
  python code/build_by_succession_table.py --analysis-dir <output folder of the estimation>
"""
import argparse
import csv
import os
from pathlib import Path
from statistics import mean

NAMES = {1940: "\\'Avila Camacho", 1946: "Alem\\'an", 1952: "Ruiz Cortines", 1958: "L\\'opez Mateos", 1964: "D\\'iaz Ordaz",
         1970: "Echeverr\\'ia", 1976: "L\\'opez Portillo", 1982: "de la Madrid", 1988: "Salinas"}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    default = os.environ.get("TAPADOS_MAIN_OUTPUT_DIR") or str(
        Path(os.environ.get("TAPADOSPRI_DB_ROOT", Path.home() / "Dropbox" / "TapadosPRI")) / "output" / "main_direct_tie")
    ap.add_argument("--analysis-dir", type=Path, default=Path(default))
    ap.add_argument("--equal-weights", action="store_true", help="equal weight per succession instead of the designee's followers' shares")
    a = ap.parse_args()
    es = [r for r in csv.DictReader(open(a.analysis_dir / "event_study_by_succession.csv")) if r["outcome"] == "rank"]
    by = {}
    for r in es:
        try:
            k = int(float(r["k"]))
        except ValueError:      # summary rows such as 'main_window'
            continue
        if 1 <= k <= 4:
            by.setdefault(int(r["election"]), []).append(float(r["estimate"]))
    avg = {e: mean(v) for e, v in by.items()}
    assert all(len(v) == 4 for v in by.values()) and len(avg) == 9
    sz = {int(r["election"]): r for r in csv.DictReader(open(a.analysis_dir / "sample_by_succession.csv"))}
    cols = list(next(iter(sz.values())).keys())
    cD = next(c for c in cols if "winner" in c or "designee" in c.lower())
    cP = next(c for c in cols if "loser" in c.lower())
    nDe = {e: int(float(sz[e][cD])) for e in avg}
    wsum = lambda es: (sum(avg[e] * (1 if a.equal_weights else nDe[e]) for e in es) / sum((1 if a.equal_weights else nDe[e]) for e in es))
    pooled = wsum(list(avg))
    out = ["% Generated by code/build_by_succession_table.py: average event-study contrast over years 1 to 4, by succession;"
           + (" pooled with equal weights." if a.equal_weights else " pooled with the designee's followers' shares (main estimand)."),
           r"\begin{tabular}{llrrrr}", r"\toprule",
           r" & & \multicolumn{2}{c}{Followers} & & Estimate without \\", r"\cmidrule(lr){3-4}",
           r"Succession & Designee & Designee's & Losers' & Estimate & this succession \\", r"\midrule"]
    for e in sorted(avg):
        loo = wsum([ee for ee in avg if ee != e])
        out.append(f"{e} & {NAMES[e]} & {int(float(sz[e][cD]))} & {int(float(sz[e][cP]))} & {avg[e]:.2f} & {loo:.2f} \\\\")
    nD = sum(int(float(sz[e][cD])) for e in avg); nP = sum(int(float(sz[e][cP])) for e in avg)
    out += [r"\midrule", f"Pooled & & {nD} & {nP} & {pooled:.2f} & \\\\", r"\bottomrule", r"\end{tabular}"]
    root = a.analysis_dir   # tables/ next to the estimates
    (root / "tables").mkdir(exist_ok=True)
    (root / "tables" / "md_by_succession.tex").write_text("\n".join(out) + "\n")
    loo = {e: wsum([ee for ee in avg if ee != e]) for e in avg}
    hi = max(avg, key=avg.get); lo = min(avg, key=avg.get)
    macros = ["% by_succession_macros.tex (build_by_succession_table.py). Do not edit by hand.",
              f"\\newcommand{{\\BSlooMin}}{{{min(loo.values()):.2f}}}", f"\\newcommand{{\\BSlooMax}}{{{max(loo.values()):.2f}}}",
              f"\\newcommand{{\\BSlooMinYear}}{{{min(loo, key=loo.get)}}}", f"\\newcommand{{\\BSlooMaxYear}}{{{max(loo, key=loo.get)}}}",
              f"\\newcommand{{\\BShighYear}}{{{hi}}}", f"\\newcommand{{\\BShighEst}}{{{avg[hi]:.2f}}}", f"\\newcommand{{\\BShighName}}{{{NAMES[hi]}}}",
              f"\\newcommand{{\\BSlowYear}}{{{lo}}}", f"\\newcommand{{\\BSlowEst}}{{{avg[lo]:.2f}}}", f"\\newcommand{{\\BSlowName}}{{{NAMES[lo]}}}",
              f"\\newcommand{{\\BSpositive}}{{{sum(v > 0 for v in avg.values())}}}"]
    (root / "tables" / "by_succession_macros.tex").write_text("\n".join(macros) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
