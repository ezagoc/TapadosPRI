"""Official pay along the office ladder, 1927 and 1999, in thousands of 2025 pesos a month.

Writes tables/rank_pay_check.tex (in the analysis output folder) for the appendix slide "Official pay along the ladder".
Pay lines are transcribed from the two sources (verified in the ranking review of 26 October 2026):
  1927  Presupuesto de Egresos de la Federación 1927, "cuota diaria" per office: Congress p. 13,
        Supreme Court p. 25, Secretaría de Gobernación pp. 45-46, Dirección General de Correos p. 172.
  1999  Exposición de motivos, PEF 2000, Table VI.4 (p. 29): monthly ordinary-pay ranges of the
        federal command posts; the midpoint is shown.
Price conversion to 2025 pesos takes the two factors already in data/rank/official_pay_real.csv
(02-rank/03_official_pay_real.py): 1927 monthly pay (daily x 365/12) -> 2025 pesos through the chained
index (level uncertain by about 20%), 1999 -> 2025 through the CPI.
Run:  python3 slides/deck/build_pay_table.py [--data-root ~/Dropbox/TapadosPRI]
"""
import argparse
import csv
import os
from pathlib import Path

# (office as shown, score on the 0-10 scale, 1927 daily pesos or (low, high), 1999 monthly range or None)
LINES = [
    ("President of the Republic",        "10",    200.0,        (106375.47, 106375.47)),
    ("Cabinet secretary",                "9",     54.0,         (88278, 88278)),
    ("Supreme Court justice",            "7",     60.0,         None),
    ("Undersecretary",                   "7",     45.0,         (80085, 83768)),
    ("Senator / federal deputy",         "7 / 4", 33.3,         None),
    ("Director general",                 "6",     41.5,         (51193, 72061)),
    ("Deputy director general",          "5",     None,         (39163, 63036)),
    ("Area director",                    "4",     None,         (24676, 41473)),
    ("Subdirector",                      "3",     27.0,         (13435, 23285)),
    ("Department head",                  "3",     (18.0, 28.0), (10013, 15218)),
]


def factors(path):
    rows = list(csv.DictReader(open(path)))
    cab = next(r for r in rows if r["office"] == "Cabinet secretary")
    f27 = float(cab["pay_1927_monthly_2025_pesos"]) / float(cab["pay_1927_monthly_1927_pesos"])
    f99 = float(cab["price_ratio_2025_1999"])
    return f27, f99


def k(x):
    return f"{x / 1000:,.0f}"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data-root", type=Path,
                    default=Path(os.environ.get("TAPADOSPRI_DB_ROOT", Path.home() / "Dropbox" / "TapadosPRI")))
    a = ap.parse_args()
    f27, f99 = factors(a.data_root / "data" / "rank" / "official_pay_real.csv")
    root = Path(os.environ.get("TAPADOS_MAIN_OUTPUT_DIR", a.data_root / "output" / "slides" / "analysis"))   # tables/ next to the estimates
    (root / "tables").mkdir(parents=True, exist_ok=True)
    out = [
        "% Generated by slides/deck/build_pay_table.py: thousands of 2025 pesos a month.",
        f"% 1927: daily rate x 365/12 x {f27:.1f}; 1999: midpoint of the range x {f99:.3f}.",
        r"\begin{tabular}{lcrr}",
        r"\toprule",
        r"Office & Score & 1927 & 1999 \\",
        r"\midrule",
    ]
    for office, score, d27, r99 in LINES:
        if d27 is None:
            c27 = "---"
        elif isinstance(d27, tuple):
            c27 = f"{k(d27[0] * 365 / 12 * f27)}--{k(d27[1] * 365 / 12 * f27)}"
        else:
            c27 = k(d27 * 365 / 12 * f27)
        c99 = "---" if r99 is None else k((r99[0] + r99[1]) / 2 * f99)
        out.append(f"{office} & {score} & {c27} & {c99} \\\\")
    out += [r"\bottomrule", r"\end{tabular}"]
    (root / "tables" / "rank_pay_check.tex").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
