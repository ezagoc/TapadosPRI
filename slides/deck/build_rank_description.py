"""Build the presentation's final sample table and baseline-rank description.

Reads canonical saved estimates and ranked spells; never reruns estimation or
writes to the shared data directory. Run from the slides repository with:
python /path/to/build_rank_description.py --data-root /path/to/TapadosPRI
"""

import argparse
import csv
import hashlib
import json
import math
from collections import Counter, defaultdict
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
import numpy as np


OFFICES = {
    9: "Cabinet secretary / head of a large state firm",
    8: "Major-state governor / PRI president",
    7: "Undersecretary / senator / Supreme Court justice",
    6: "Director general / other governor",
    5: "Deputy director general / big-city mayor",
    4: "Area director / federal deputy",
    3: "Department head / state legislator",
    2: "Mayor / staff / union officer",
    1: "Municipal councillor / local party official",
    0: "No recorded ranked office",
}
DESIGNEES = [
    r"\'Avila Camacho", r"Alem\'an", "Ruiz Cortines", r"L\'opez Mateos",
    r"D\'iaz Ordaz", r"Echeverr\'ia", r"L\'opez Portillo", "de la Madrid", "Salinas",
]


def read_csv(path):
    with path.open(newline="", encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def number(x):
    return int(float(x))


def write_csv(path, rows):
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)


def annual_ranks(rows):
    annual = {}
    for row in rows:
        try:
            rank = math.floor(float(row["hybrid_rank"]) + 1e-9)
            start = number(row["year_start"])
            end = max(start, number(row["year_end"])) if row["year_end"] not in ("", "NA") else start
            pid = number(row["person_id"])
        except (ValueError, TypeError):
            continue
        if not 1 <= rank <= 11 or end - start > 12:
            continue
        assert rank == 13 - number(row["brandenburg_rung"])
        for year in range(start, end + 1):
            key = (pid, year)
            annual[key] = max(annual.get(key, 0), rank)
    return annual


def sample_table(flow, path):
    flow = sorted(flow, key=lambda x: number(x["election"]))
    assert [number(x["election"]) for x in flow] == list(range(1940, 1989, 6))
    lines = [
        "% Generated by code/build_rank_description.py from canonical sample_by_succession.csv.",
        r"\begin{tabular}{llrrrrr}",
        r"\toprule",
        r" & & & & \multicolumn{3}{c}{Connected to exactly one contender} \\",
        r"\cmidrule(lr){5-7}",
        r"Succession & Designee & Contender & Eligible & Designee's & All losing & Largest losing \\",
        r" & & set (N) & politicians & network & networks & network \\",
        r"\midrule",
    ]
    for name, row in zip(DESIGNEES, flow):
        values = [
            str(number(row["election"])), name, str(number(row["slate_size"])),
            f'{number(row["eligible"]):,}', f'{number(row["winner_followers"]):,}',
            f'{number(row["loser_followers"]):,}', f'{number(row["largest_loser"]):,}',
        ]
        lines.append(" & ".join(values) + r" \\")
    sums = {k: sum(number(row[k]) for row in flow) for k in (
        "slate_size", "eligible", "winner_followers", "loser_followers")}
    values = ["Total", "", f'{sums["slate_size"]:,}', f'{sums["eligible"]:,}',
              f'{sums["winner_followers"]:,}', f'{sums["loser_followers"]:,}', ""]
    lines += [r"\midrule", " & ".join(values) + r" \\", r"\bottomrule", r"\end{tabular}"]
    path.write_text("\n".join(lines) + "\n")




def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-root", type=Path, required=True)
    parser.add_argument("--analysis-dir", type=Path)
    args = parser.parse_args()
    analysis = args.analysis_dir or args.data_root / "output/slides/analysis"
    root = analysis   # tables/sample.tex and the audit go next to the estimates
    (root / "tables").mkdir(exist_ok=True)
    files = {
        "analysis_sample": analysis / "analysis_sample.csv",
        "sample_by_succession": analysis / "sample_by_succession.csv",
        "position_tiers": args.data_root / "data/rank/position_tiers.csv",
        "official_pay": args.data_root / "data/rank/official_pay_real.csv",
    }
    sample = read_csv(files["analysis_sample"])
    assert len({(row["pid"], row["election"]) for row in sample}) == len(sample)
    cohorts = sorted({number(row["election"]) for row in sample})
    assert cohorts == list(range(1940, 1989, 6))
    annual = annual_ranks(read_csv(files["position_tiers"]))
    buckets = defaultdict(list)
    for row in sample:
        pid, election, group = number(row["pid"]), number(row["election"]), number(row["treated"])
        pre = max(annual.get((pid, year), 0) for year in range(election - 5, election - 1))
        assert pre == number(row["pre"]), "The saved analysis sample and current ranked spells differ."
        rank = annual.get((pid, election - 2), 0)
        assert rank in OFFICES
        buckets[(group, election)].append(rank)
    stats = []
    shares = {}
    labels = {1: "Connected to the designee", 0: "Connected to a losing contender"}
    audit = {
        "sample_n": len(sample),
        "unique_politicians": len({row["pid"] for row in sample}),
        "cohorts": cohorts,
        "time": "annual rank in e-2; e is the election year",
        "weighting": "mean of nine within-succession distributions, separately by group",
        "source_sha256": {name: hashlib.sha256(path.read_bytes()).hexdigest() for name, path in files.items()},
        "groups": {},
    }
    for group in (1, 0):
        counts = Counter(x for e in cohorts for x in buckets[(group, e)])
        shares[group] = [
            100 * sum(buckets[(group, e)].count(rank) / len(buckets[(group, e)]) for e in cohorts) / len(cohorts)
            for rank in range(10)
        ]
        assert abs(sum(shares[group]) - 100) < 1e-9
        audit["groups"][str(group)] = {
            "label": labels[group], "n": sum(counts.values()),
            "mean_rank_equal_succession": sum(rank * p / 100 for rank, p in enumerate(shares[group])),
        }
        for rank in range(10):
            stats.append({
                "group": labels[group], "rank_score": rank, "office_examples": OFFICES[rank],
                "politician_successions": counts[rank], "share_equal_succession_percent": shares[group][rank],
            })
    flow = read_csv(files["sample_by_succession"])
    for row in flow:
        e = number(row["election"])
        assert len(buckets[(1, e)]) == number(row["winner_followers"])
        assert len(buckets[(0, e)]) == number(row["loser_followers"])
    write_csv(root / "tables/sample_rank_distribution.csv", stats)
    sample_table(flow, root / "tables/sample.tex")
    # tables/rank_pay_check.tex is written by code/build_pay_table.py
    (root / "tables/rank_description_audit.json").write_text(json.dumps(audit, indent=2) + "\n")

    plt.rcParams.update({
        "font.family": "sans-serif", "font.sans-serif": ["Helvetica", "Arial", "DejaVu Sans"],
        "font.size": 9, "pdf.fonttype": 42, "axes.spines.top": False, "axes.spines.right": False,
        "axes.spines.left": False, "axes.spines.bottom": False,
    })
    fig, ax = plt.subplots(figsize=(6.0, 2.2))
    ranks = list(range(9, -1, -1))
    y = np.arange(len(ranks))
    for pos in y:
        ax.axhline(pos, color="#e7e7e7", lw=0.5, zorder=0)
    for group, color, marker, shift in ((1, "#940034", "o", -.09), (0, "#252525", "D", .09)):
        ax.scatter([shares[group][rank] for rank in ranks], y + shift, s=22,
                   marker=marker, facecolors=color if group else "white",
                   edgecolors=color, linewidths=.8, zorder=3)
    ax.set_yticks(y, [f"{rank}   {OFFICES[rank]}" for rank in ranks])
    ax.invert_yaxis()
    ax.tick_params(axis="y", length=0, pad=8, labelsize=8.5)
    ax.tick_params(axis="x", length=3, color="#777777")
    maximum = 5 * math.ceil(max(max(p) for p in shares.values()) / 5)
    ax.set_xlim(-.5, maximum + .5)
    ax.set_xticks(np.arange(0, maximum + 1, 5))
    ax.set_xlabel("Share of politicians (%)", labelpad=6)
    handles = [
        Line2D([], [], color="#940034", marker="o", linestyle="None", markersize=4.6,
               label=labels[1]),
        Line2D([], [], color="#252525", marker="D", markerfacecolor="white",
               linestyle="None", markersize=4.2, label=labels[0]),
    ]
    fig.legend(handles=handles, loc="upper center", ncol=1, frameon=False,
               fontsize=8.0, bbox_to_anchor=(.77, 1.02), handletextpad=.5, labelspacing=.25)
    fig.subplots_adjust(left=.59, right=.97, top=.79, bottom=.20)
    fig.savefig(root / "sample_rank_distribution.pdf", facecolor="white")
    plt.close(fig)
    print(json.dumps({k: audit[k] for k in ("sample_n", "unique_politicians", "groups")}, indent=2))


if __name__ == "__main__":
    main()
